    private Object instantiate(Class<?> compiledClass) {
        return withRuntimeContext(() -> {
            try {
                return compiledClass.getDeclaredConstructor().newInstance();
            } catch (InstantiationException
                    | IllegalAccessException
                    | InvocationTargetException
                    | NoSuchMethodException e) {
                throw new LPCRuntimeException("Failed to instantiate LPC object: " + compiledClass.getName(), e);
            }
        });
    }

    private void forEachInventory(Object container, Consumer<Object> action) {
        Object child = runtimeContext.firstInventory(container);
        while (child != null) {
            Object next = runtimeContext.nextInventory(child);
            action.accept(child);
            child = next;
        }
    }

    private void resetIfPresent(Object object) {
        invokeLifecycleIfPresent(MudlibLifecycleEvent.OBJECT_LOADED, object, 0);
    }

    private void invokeLifecycleIfPresent(MudlibLifecycleEvent event, Object object, Object... args) {
        String methodName = mudlibBoundary.lifecycleMethod(event).orElse(null);
        if (methodName == null) {
            return;
        }

        withRuntimeContext(() -> runtimeContext.invokeOptionalObject(object, methodName, args));
    }

    private Class<?>[] parameterTypes(Object[] args) {
        Class<?>[] types = new Class<?>[args.length];
        for (int i = 0; i < args.length; i++) {
            types[i] = Object.class;
        }
        return types;
    }

    private List<LPCObjectInspection.FieldValue> inspectFields(Object object) {
        List<LPCObjectInspection.FieldValue> fields = new ArrayList<>();
        Class<?> type = object.getClass();
        while (type != null && type != Object.class) {
            for (Field field : type.getDeclaredFields()) {
                if (field.isSynthetic()) {
                    continue;
                }
                try {
                    field.setAccessible(true);
                    fields.add(new LPCObjectInspection.FieldValue(
                            type.getName(),
                            mudName(type),
                            friendlyTypeName(field.getType()),
                            field.getName(),
                            displayValue(field.get(object))));
                } catch (IllegalAccessException e) {
                    fields.add(new LPCObjectInspection.FieldValue(
                            type.getName(),
                            mudName(type),
                            friendlyTypeName(field.getType()),
                            field.getName(),
                            "<inaccessible>"));
                }
            }
            type = type.getSuperclass();
        }
        fields.sort(Comparator
                .comparing(LPCObjectInspection.FieldValue::ownerClass)
                .thenComparing(LPCObjectInspection.FieldValue::name));
        return fields;
    }

    private void forEachPersistentField(Object object, Consumer<Field> action) {
        Class<?> type = object.getClass();
        while (type != null && type != Object.class) {
            for (Field field : type.getDeclaredFields()) {
                int modifiers = field.getModifiers();
                if (field.isSynthetic() || Modifier.isStatic(modifiers)) {
                    continue;
                }
                action.accept(field);
            }
            type = type.getSuperclass();
        }
    }

    private String fieldKey(Field field) {
        return field.getDeclaringClass().getName() + "." + field.getName();
    }

    private PersistentValue encodePersistentValue(Object value) {
        if (value == null) {
            return new PersistentValue("null", null);
        }
        if (value instanceof String text) {
            return new PersistentValue("string", text);
        }
        if (value instanceof Integer number) {
            return new PersistentValue("int", number);
        }
        if (value instanceof Boolean bool) {
            return new PersistentValue("boolean", bool);
        }
        return null;
    }

    private Object decodePersistentValue(PersistentValue encoded, Class<?> targetType) {
        if ("null".equals(encoded.type())) {
            return targetType.isPrimitive() ? UnsupportedValue.INSTANCE : null;
        }
        if ((targetType == String.class || targetType == Object.class) && "string".equals(encoded.type())) {
            return encoded.value();
        }
        if ((targetType == int.class || targetType == Integer.class || targetType == Object.class)
                && "int".equals(encoded.type())) {
            return encoded.value() instanceof Number number
                    ? Integer.valueOf(number.intValue())
                    : UnsupportedValue.INSTANCE;
        }
        if ((targetType == boolean.class || targetType == Boolean.class || targetType == Object.class)
                && "boolean".equals(encoded.type())) {
            return encoded.value() instanceof Boolean ? encoded.value() : UnsupportedValue.INSTANCE;
        }
        return UnsupportedValue.INSTANCE;
    }

    private Map<String, PersistentValue> readLPCObjectState(Path path) throws IOException {
        String text = Files.readString(path);
        if (text.trim().startsWith("{")) {
            LPCObjectStateFile state = JSON.readValue(text, LPCObjectStateFile.class);
            return state.fields() != null ? state.fields() : Map.of();
        }
        return readLegacyPropertiesObjectState(path);
    }

    private Map<String, PersistentValue> readLegacyPropertiesObjectState(Path path) throws IOException {
        Properties properties = new Properties();
        try (var reader = Files.newBufferedReader(path)) {
            properties.load(reader);
        }
        Map<String, PersistentValue> fields = new LinkedHashMap<>();
        for (String name : properties.stringPropertyNames()) {
            PersistentValue value = decodeLegacyPersistentValue(properties.getProperty(name));
            if (value != null) {
                fields.put(name, value);
            }
        }
        return fields;
    }

    private PersistentValue decodeLegacyPersistentValue(String encoded) {
        int separator = encoded.indexOf(':');
        if (separator < 0) {
            return null;
        }
        String kind = encoded.substring(0, separator);
        String value = encoded.substring(separator + 1);
        return switch (kind) {
            case "null" -> new PersistentValue("null", null);
            case "string" -> new PersistentValue("string", value);
            case "int" -> {
                try {
                    yield new PersistentValue("int", Integer.valueOf(value));
                } catch (NumberFormatException e) {
                    yield null;
                }
            }
            case "boolean" -> new PersistentValue("boolean", Boolean.valueOf(value));
            default -> null;
        };
    }

    private record LPCObjectStateFile(String format, int version, Map<String, PersistentValue> fields) {}

    private record PersistentValue(String type, Object value) {}

    private enum UnsupportedValue {
        INSTANCE
    }

    private List<LPCObjectInspection.MethodSignature> inspectMethods(Object object) {
        List<LPCObjectInspection.MethodSignature> methods = new ArrayList<>();
        for (Method method : object.getClass().getMethods()) {
            if (method.isSynthetic() || method.isBridge() || method.getDeclaringClass() == Object.class) {
                continue;
            }
            if (!Modifier.isPublic(method.getModifiers())) {
                continue;
            }
            List<String> parameterTypes = new ArrayList<>();
            for (Class<?> parameterType : method.getParameterTypes()) {
                parameterTypes.add(friendlyTypeName(parameterType));
            }
            methods.add(new LPCObjectInspection.MethodSignature(
                    method.getDeclaringClass().getName(),
                    mudName(method.getDeclaringClass()),
                    friendlyTypeName(method.getReturnType()),
                    method.getName(),
                    parameterTypes));
        }
        methods.sort(Comparator
                .comparing(LPCObjectInspection.MethodSignature::name)
                .thenComparingInt(method -> method.parameterTypes().size())
                .thenComparing(LPCObjectInspection.MethodSignature::ownerClass));
        return methods;
    }

    private String mudName(Class<?> type) {
        return type.getName().replace('.', '/');
    }

    private String displayValue(Object value) {
        if (value == null) {
            return "0";
        }
        if (value instanceof String text) {
            return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\"";
        }
        if (value instanceof Number || value instanceof Boolean) {
            return value.toString();
        }
        return objectReference(value);
    }

    private String objectReference(Object object) {
        String objectId = runtimeContext.objectId(object);
        return objectId != null ? objectId : object.toString();
    }

    private String friendlyTypeName(Class<?> type) {
        if (type == void.class) {
            return "void";
        }
        if (type == int.class || type == Integer.class) {
            return "int";
        }
        if (type == boolean.class || type == Boolean.class) {
            return "status";
        }
        if (type == String.class) {
            return "string";
        }
        if (type == Object.class) {
            return "mixed";
        }
        return type.getSimpleName();
    }

    private Class<?> ensureClassDefined(Path sourcePath, String objectId, String internalName) {
        if (classLoader.isDefined(internalName)) {
            try {
                return classLoader.loadClass(internalName.replace('/', '.'));
            } catch (ClassNotFoundException e) {
                throw new LPCRuntimeException("Defined LPC class could not be loaded: " + internalName, e);
            }
        }

        String source;
        try {
            source = Files.readString(sourcePath);
        } catch (IOException e) {
            throw new LPCRuntimeException("Failed to read source file: " + sourcePath, e);
        }

        CompilationResult result =
                pipeline.run(sourcePath, source, internalName, "/" + objectId, ParserOptions.defaults());
        if (!result.getProblems().isEmpty()) {
            throw compilationFailure(objectId, result.getProblems());
        }

        CompilationUnit compilationUnit = result.getCompilationUnit();
        if (compilationUnit != null) {
            defineInheritedClasses(compilationUnit.parentUnit());
        }

        byte[] bytecode = result.getBytecode();
        if (bytecode == null) {
            throw new LPCRuntimeException("Compilation did not produce bytecode for " + internalName);
        }

        return classLoader.defineClass(internalName, bytecode);
    }

    private void registerObject(String baseName, Object object) {
        String objectId = baseName;
        int suffix = 1;
        while (runtimeContext.getObject(objectId) != null) {
            objectId = baseName + "#" + suffix;
            suffix++;
        }
        runtimeContext.registerObject(objectId, object);
    }

    private String nextCloneId(String internalName) {
        String objectId = internalName + "#clone";
        int suffix = 1;
        while (runtimeContext.getObject(objectId) != null) {
            objectId = internalName + "#clone" + suffix;
            suffix++;
        }
        return objectId;
    }

    private Path resolveSourcePath(String sourcePath) {
        Path raw = Path.of(sourcePath);
        if (raw.isAbsolute() && baseIncludePath != null) {
            String trimmed = sourcePath;
            while (trimmed.startsWith("/")) {
                trimmed = trimmed.substring(1);
            }
            if (!trimmed.isEmpty()) {
                Path baseCandidate = baseIncludePath.resolve(trimmed).normalize();
                if (Files.exists(baseCandidate)) {
                    return baseCandidate;
                }
                Path mudlibRoot = mudlibBoundary.mudlibRootPath().orElse(null);
                if (mudlibRoot != null) {
                    Path mudlibCandidate = mudlibRoot.resolve(trimmed).normalize();
                    if (Files.exists(mudlibCandidate)) {
                        return mudlibCandidate;
                    }
                }
                return baseCandidate;
            }
        }

        if (!raw.isAbsolute() && baseIncludePath != null) {
            Path baseCandidate = baseIncludePath.resolve(raw).normalize();
            if (Files.exists(baseCandidate)) {
                return baseCandidate;
            }
            Path mudlibRoot = mudlibBoundary.mudlibRootPath().orElse(null);
            if (mudlibRoot != null) {
                Path mudlibCandidate = mudlibRoot.resolve(raw).normalize();
                if (Files.exists(mudlibCandidate)) {
                    return mudlibCandidate;
                }
            }
            return baseCandidate;
        }

        return raw.normalize();
    }

    private Path resolveMudlibStoragePath(String path) {
        if (baseIncludePath == null) {
            return null;
        }
        String normalized = normalizeMudlibStoragePath(path);
        if (normalized == null) {
            return null;
        }
        return resolveMudlibPathUnder(baseIncludePath, normalized);
    }

    private Path resolveMudlibTextPath(String path) {
        Path mudlibRoot = mudlibBoundary.mudlibRootPath().orElse(null);
        if (mudlibRoot == null) {
            return null;
        }
        String normalized = normalizeMudlibStoragePath(path);
        if (normalized == null) {
            return null;
        }
        return resolveMudlibPathUnder(mudlibRoot, normalized);
    }

    private String normalizeMudlibStoragePath(String path) {
        String normalized = path.trim();
        while (normalized.startsWith("/")) {
            normalized = normalized.substring(1);
        }
        if (normalized.isBlank()) {
            return null;
        }
        for (Path segment : Path.of(normalized)) {
            if (segment.toString().equals("..")) {
                return null;
            }
        }
        return normalized;
    }

    private Path resolveMudlibPathUnder(Path root, String normalizedPath) {
        Path normalizedRoot = root.toAbsolutePath().normalize();
        Path resolved = normalizedRoot.resolve(normalizedPath).normalize();
        return resolved.startsWith(normalizedRoot) ? resolved : null;
    }

    private Path resolveSourcePathWithExtensions(String sourcePath) {
        Path resolved = resolveSourcePath(sourcePath);
        if (hasExtension(resolved)) {
            return resolved;
        }
        if (Files.exists(resolved)) {
            return resolved;
        }
        Path cCandidate = resolveSourcePath(sourcePath + ".c");
        if (Files.exists(cCandidate)) {
            return cCandidate;
        }
        Path lpcCandidate = resolveSourcePath(sourcePath + ".lpc");
        if (Files.exists(lpcCandidate)) {
            return lpcCandidate;
        }
        return resolved;
    }

    private Path resolveSourcePathWithExtensions(Path sourcePath) {
        Path normalized = normalizeSourcePath(sourcePath);
        if (hasExtension(sourcePath)) {
            return normalized;
        }
        if (Files.exists(normalized)) {
            return normalized;
        }
        Path cCandidate = normalizeSourcePath(appendExtension(sourcePath, ".c"));
        if (Files.exists(cCandidate)) {
            return cCandidate;
        }
        Path lpcCandidate = normalizeSourcePath(appendExtension(sourcePath, ".lpc"));
        if (Files.exists(lpcCandidate)) {
            return lpcCandidate;
        }
        return normalized;
    }

    private Path normalizeSourcePath(Path sourcePath) {
        Path normalized = sourcePath;
        if (!normalized.isAbsolute() && baseIncludePath != null) {
            normalized = baseIncludePath.resolve(normalized);
        }
        return normalized.toAbsolutePath().normalize();
    }

    private Path sourceNameBasePath(Path sourcePath) {
        Path mudlibRoot = mudlibBoundary.mudlibRootPath().orElse(null);
        if (mudlibRoot != null && sourcePath.normalize().startsWith(mudlibRoot.normalize())) {
            return mudlibRoot;
        }
        return baseIncludePath;
    }

    private Path appendExtension(Path sourcePath, String extension) {
        Path fileName = sourcePath.getFileName();
        if (fileName == null) {
            return sourcePath;
        }
        Path parent = sourcePath.getParent();
        String nameWithExtension = fileName.toString() + extension;
        return (parent == null) ? Path.of(nameWithExtension) : parent.resolve(nameWithExtension);
    }

    private boolean hasExtension(Path sourcePath) {
        Path fileName = sourcePath.getFileName();
        if (fileName == null) {
            return false;
        }
        String name = fileName.toString();
        return name.endsWith(".c") || name.endsWith(".lpc");
    }

    private String formatProblems(List<CompilationProblem> problems) {
        StringBuilder builder = new StringBuilder("Compilation failed:\n");
        for (CompilationProblem problem : problems) {
            builder.append("- ")
                    .append(problem.getStage())
                    .append(": ")
                    .append(problem.getMessage());
            if (problem.getLine() != null) {
                builder.append(" (line ").append(problem.getLine()).append(")");
            }
            Throwable throwable = problem.getThrowable();
            if ((throwable != null) && (throwable.getMessage() != null)) {
                builder.append(" - ").append(throwable.getMessage());
            }
            builder.append("\n");
        }
        return builder.toString();
    }

    private LPCRuntimeException compilationFailure(String objectId, List<CompilationProblem> problems) {
        String message = formatProblems(problems);
        notifyCompilationError(objectId, message);
        return new LPCRuntimeException(message, problems);
    }

    /**
     * Gives the mudlib a chance to satisfy a shared-object path whose source file is absent.
     *
     * <p>This is intentionally phrased as a missing-source hook rather than a virtual-object
     * primitive. JVMud only knows that normal source lookup failed for {@code objectId}. If the
     * mudlib returns an already-registered runtime object, that object becomes the canonical shared
     * object for {@code objectId}; future {@link #loadOrGetObject(String)} calls return it from the
     * object table before touching the filesystem or notifying the mudlib again. Returning LPC
     * false, or returning a non-object scalar by mistake, keeps the ordinary source-not-found path,
     * including compile-error notification.</p>
     */
    private Object notifyObjectSourceMissing(String objectId) {
        String methodName = mudlibBoundary.lifecycleMethod(MudlibLifecycleEvent.OBJECT_SOURCE_MISSING).orElse(null);
        String boundaryObjectPath = mudlibBoundary.boundaryObjectPath().orElse(null);
        if (methodName == null || boundaryObjectPath == null || notifyingObjectSourceMissing) {
            return null;
        }

        String normalizedObjectId = normalizeInternalName(objectId);
        String normalizedBoundaryPath = normalizeInternalName(boundaryObjectPath);
        if (normalizedBoundaryPath.equals(normalizedObjectId)) {
            return null;
        }

        notifyingObjectSourceMissing = true;
        try {
            Object handler = loadOrGetObject(normalizedBoundaryPath);
            Object supplied = invokeOptionalObject(handler, methodName, normalizedObjectId);
            clearOutputTranscript();
            if (isLpcFalse(supplied)) {
                return null;
            }
            if (runtimeContext.objectId(supplied) == null) {
                return null;
            }
            runtimeContext.registerObject(normalizedObjectId, supplied);
            return supplied;
        } catch (RuntimeException | LinkageError ignored) {
            clearOutputTranscript();
            return null;
        } finally {
            notifyingObjectSourceMissing = false;
        }
    }

    private void notifyCompilationError(String objectId, String message) {
        String methodName = mudlibBoundary.lifecycleMethod(MudlibLifecycleEvent.LOG_ERROR).orElse(null);
        String boundaryObjectPath = mudlibBoundary.boundaryObjectPath().orElse(null);
        if (methodName == null || boundaryObjectPath == null || notifyingCompilationError) {
            return;
        }

        String normalizedObjectId = normalizeInternalName(objectId);
        String normalizedBoundaryPath = normalizeInternalName(boundaryObjectPath);
        if (normalizedBoundaryPath.equals(normalizedObjectId)) {
            return;
        }

        notifyingCompilationError = true;
        try {
            Object handler = loadOrGetObject(normalizedBoundaryPath);
            invokeOptionalObject(handler, methodName, "/" + normalizedObjectId, message);
            clearOutputTranscript();
        } catch (RuntimeException | LinkageError ignored) {
            clearOutputTranscript();
        } finally {
            notifyingCompilationError = false;
        }
    }

    private void notifyTimedRuntimeError(Object target, String context, String operation, Throwable error) {
        String boundaryObjectPath = mudlibBoundary.boundaryObjectPath().orElse(null);
        if (boundaryObjectPath == null || notifyingTimedRuntimeError) {
            return;
        }

        notifyingTimedRuntimeError = true;
        try {
            Object handler = loadOrGetObject(boundaryObjectPath);
            String detail = error.getMessage() != null ? error.getMessage() : error.getClass().getSimpleName();
            String objectId = runtimeContext.objectId(target);
            if (objectId == null) {
                objectId = String.valueOf(target);
            }

            String runtimeErrorMethod = mudlibBoundary.lifecycleMethod(MudlibLifecycleEvent.RUNTIME_ERROR).orElse(null);
            if (runtimeErrorMethod != null) {
                invokeOptionalObject(handler, runtimeErrorMethod, target, context, operation, detail);
                clearOutputTranscript();
            }

            if ("scheduled_tick".equals(context)) {
                String scheduledTickErrorMethod =
                        mudlibBoundary.lifecycleMethod(MudlibLifecycleEvent.SCHEDULED_TICK_ERROR).orElse(null);
                if (scheduledTickErrorMethod != null) {
                    invokeOptionalObject(handler, scheduledTickErrorMethod, target, detail, objectId, objectId, 0);
                    clearOutputTranscript();
                }
            }
        } catch (RuntimeException | LinkageError ignored) {
            clearOutputTranscript();
        } finally {
            notifyingTimedRuntimeError = false;
        }
    }

    private Object notifyObjectDestructionRequested(Object target) {
        String methodName = mudlibBoundary.lifecycleMethod(MudlibLifecycleEvent.OBJECT_DESTRUCTION_REQUESTED).orElse(null);
        String boundaryObjectPath = mudlibBoundary.boundaryObjectPath().orElse(null);
        if (methodName == null || boundaryObjectPath == null || notifyingObjectDestructionRequested) {
            return 0;
        }

        notifyingObjectDestructionRequested = true;
        try {
            Object handler = loadOrGetObject(boundaryObjectPath);
            Object result = invokeOptionalObject(handler, methodName, target);
            clearOutputTranscript();
            return result;
        } catch (RuntimeException | LinkageError e) {
            clearOutputTranscript();
            return 1;
        } finally {
            notifyingObjectDestructionRequested = false;
        }
    }

    private boolean isLpcFalse(Object value) {
        return value == null || Integer.valueOf(0).equals(value);
    }

    private String normalizeInternalName(String internalName) {
        String normalized = internalName;
        while (normalized.startsWith("/")) {
            normalized = normalized.substring(1);
        }
        return normalized;
    }

    private String jvmInternalName(String objectId) {
        return objectId.replace(".", "$dot$");
    }

    private String deriveSourceName(Path sourcePath, Path basePath) {
        Path normalized = sourcePath.normalize();
        Path base = (basePath != null) ? basePath.normalize() : null;
        Path relative = (base != null && normalized.startsWith(base))
                ? base.relativize(normalized)
                : normalized;
        Path withoutExtension = stripExtension(relative);
        String normalizedName = withoutExtension.normalize().toString().replace('\\', '/');

        while (normalizedName.startsWith("/")) {
            normalizedName = normalizedName.substring(1);
        }

        return normalizedName;
    }

    private String stripExtension(String name) {
        int dot = name.lastIndexOf('.');
        return (dot == -1) ? name : name.substring(0, dot);
    }

    private void defineInheritedClasses(CompilationUnit unit) {
        if (unit == null) {
            return;
        }

        defineInheritedClasses(unit.parentUnit());

        ASTObject astObject = unit.astObject();
        if (astObject == null) {
            return;
        }

        String internalName = normalizeInternalName(astObject.name());
        if (classLoader.isDefined(internalName)) {
            return;
        }

        CompilationResult result =
                pipeline.run(unit.sourcePath(), unit.source(), unit.sourceName(), unit.displayPath(), ParserOptions.defaults());

        if (!result.getProblems().isEmpty()) {
            throw compilationFailure(internalName, result.getProblems());
        }

        byte[] bytecode = result.getBytecode();
        if (bytecode == null) {
            throw new LPCRuntimeException("Compilation did not produce bytecode for " + internalName);
        }

        classLoader.defineClass(internalName, bytecode);
    }

    private Path stripExtension(Path path) {
        if (path == null) {
            return Path.of("<input>");
        }

        Path fileName = path.getFileName();
        if (fileName == null) {
            return path;
        }

        String name = fileName.toString();
        int dot = name.lastIndexOf('.');
        String stem = (dot == -1) ? name : name.substring(0, dot);
        Path parent = path.getParent();

        return (parent == null) ? Path.of(stem) : parent.resolve(stem);
    }
