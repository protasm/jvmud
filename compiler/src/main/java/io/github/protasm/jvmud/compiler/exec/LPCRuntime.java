    /** Reads a mudlib-relative text file, returning LPC false ({@code 0}) when unavailable. */
    public Object readMudlibText(String path) {
        Objects.requireNonNull(path, "path");
        Path resolved = resolveMudlibStoragePath(path);
        if (resolved == null || !Files.isRegularFile(resolved)) {
            resolved = resolveMudlibTextPath(path);
        }
        if (resolved == null || !Files.isRegularFile(resolved)) {
            return 0;
        }
        try {
            return Files.readString(resolved);
        } catch (IOException e) {
            return 0;
        }
    }

    /** Appends text to a mudlib-rooted file, returning LP-style success. */
    public int appendMudlibText(String path, Object text) {
        Objects.requireNonNull(path, "path");
        Path resolved = resolveMudlibTextPath(path);
        if (resolved == null) {
            resolved = resolveMudlibStoragePath(path);
        }
        if (resolved == null) {
            return 0;
        }
        try {
            Path parent = resolved.getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            Files.writeString(
                    resolved,
                    String.valueOf(text),
                    java.nio.file.StandardOpenOption.CREATE,
                    java.nio.file.StandardOpenOption.APPEND);
            return 1;
        } catch (IOException e) {
            return 0;
        }
    }

    /** Saves scalar LPC object fields to mudlib-rooted storage, returning LP-style success. */
    public int saveLPCObjectState(String path, Object object) {
        Objects.requireNonNull(path, "path");
        Objects.requireNonNull(object, "object");
        Path resolved = resolveMudlibStoragePath(path + ".o");
        if (resolved == null) {
            return 0;
        }

        Map<String, PersistentValue> fields = new LinkedHashMap<>();
        forEachPersistentField(object, field -> {
            try {
                field.setAccessible(true);
                Object value = field.get(object);
                PersistentValue persistentValue = encodePersistentValue(value);
                if (persistentValue != null) {
                    fields.put(fieldKey(field), persistentValue);
                }
            } catch (IllegalAccessException ignored) {
                // Inaccessible fields are not LPC-visible persistence state.
            }
        });

        try {
            Path parent = resolved.getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            JSON.writeValue(resolved.toFile(), new LPCObjectStateFile(
                    "jvmud.lpc-object-state",
                    1,
                    fields));
            return 1;
        } catch (IOException | IllegalArgumentException e) {
            return 0;
        }
    }

    /** Restores scalar LPC object fields from mudlib-rooted storage, returning LP-style success. */
    public int restoreLPCObjectState(String path, Object object) {
        Objects.requireNonNull(path, "path");
        Objects.requireNonNull(object, "object");
        Path resolved = resolveMudlibStoragePath(path + ".o");
        if (resolved == null || !Files.isRegularFile(resolved)) {
            return 0;
        }

        Map<String, PersistentValue> fields;
        try {
            fields = readLPCObjectState(resolved);
        } catch (IOException e) {
            return 0;
        }

        forEachPersistentField(object, field -> {
            PersistentValue encoded = fields.get(fieldKey(field));
            if (encoded == null) {
                return;
            }
            Object value = decodePersistentValue(encoded, field.getType());
            if (value == UnsupportedValue.INSTANCE) {
                return;
            }
            try {
                field.setAccessible(true);
                if (field.getType() == int.class) {
                    field.setInt(object, ((Number) value).intValue());
                } else if (field.getType() == boolean.class) {
                    field.setBoolean(object, (Boolean) value);
                } else {
                    field.set(object, value);
                }
            } catch (IllegalAccessException ignored) {
                // Ignore fields that cannot be restored on this generated class version.
            }
        });
        return 1;
    }

