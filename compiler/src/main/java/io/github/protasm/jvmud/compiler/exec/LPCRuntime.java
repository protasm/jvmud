    private final RuntimeContext runtimeContext;
    private final CompilationPipeline pipeline;
    private final Path baseIncludePath;
    private final List<Path> includeSearchPaths;
    private final boolean useBoundaryMudlibRootForIncludes;
    private MudlibBoundary mudlibBoundary = MudlibBoundary.empty();
    private boolean notifyingCompilationError;
    private boolean notifyingTimedRuntimeError;
    private boolean notifyingObjectSourceMissing;
    private boolean notifyingObjectDestructionRequested;

    public LPCRuntime(LPCRuntimeConfig config) {
        Objects.requireNonNull(config, "config");
        this.baseIncludePath = config.baseIncludePath();
        this.includeSearchPaths = config.includeSearchPaths();
        this.useBoundaryMudlibRootForIncludes = config.includeResolver() == null;
        this.runtimeContext = new RuntimeContext(config.resolveIncludeResolver());
        this.runtimeContext.setObjectFactory(this::cloneObject);
        this.runtimeContext.setObjectLoader(this::loadOrGetObject);
        this.runtimeContext.setMudlibTextReader(this::readMudlibText);
        this.runtimeContext.setMudlibTextAppender(this::appendMudlibText);
        this.runtimeContext.setLPCObjectStateSaver(this::saveLPCObjectState);
        this.runtimeContext.setLPCObjectStateRestorer(this::restoreLPCObjectState);
        this.runtimeContext.setTimedRuntimeErrorHandler(this::notifyTimedRuntimeError);
        this.runtimeContext.setObjectDestructionRequestedHandler(this::notifyObjectDestructionRequested);
        this.classLoader = new LPCRuntimeClassLoader(config.parentClassLoader());
        this.pipeline = new CompilationPipeline(config.parentInternalName(), runtimeContext, config.compilationObserver());
    }

    /**
     * Loads, compiles, instantiates, registers, and initializes one LPC source file.
     *
     * <p>Relative paths are resolved under the configured base include path. Absolute-looking mudlib
     * paths such as {@code /room/church} are also resolved under that base path when one is
     * configured.</p>
     */
    public LPCObjectHandle load(String sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        return load(resolveSourcePathWithExtensions(sourcePath));
    }

    /**
     * Returns a registered shared object for a source path, loading it if needed.
     *
     * <p>This is the host-side equivalent of resolving a mudlib singleton object rather than making
     * a clone.</p>
     */
    public Object loadOrGetObject(String sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        Path normalized = resolveSourcePathWithExtensions(sourcePath);
        String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
        Object existing = runtimeContext.getObject(objectId);
        if (existing != null) {
            return existing;
        }
        return load(normalized).instance();
    }

    /** Reloads an LPC source path, replacing the shared registered object if it already exists. */
    public LPCObjectHandle reload(String sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        return reload(resolveSourcePathWithExtensions(sourcePath));
    }

    /**
     * Reloads a source file from a filesystem path.
     *
     * <p>Reloading creates a fresh class loader because generated JVM classes cannot be redefined in
     * the same loader.</p>
     */
    public LPCObjectHandle reload(Path sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        Path normalized = resolveSourcePathWithExtensions(sourcePath);
        String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
        Object existing = runtimeContext.getObject(objectId);
        if (existing != null) {
            runtimeContext.destructObject(existing);
        }

        // JVM classes cannot be redefined in the same classloader. A fresh loader lets the
        // reloaded LPC source produce a new generated class while old live objects keep working.
        classLoader = new LPCRuntimeClassLoader(classLoader.getParent());
        return load(normalized);
    }

    /** Loads, compiles, instantiates, registers, and initializes one source file. */
    public LPCObjectHandle load(Path sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        Path normalized = resolveSourcePathWithExtensions(sourcePath);
        String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
        if (!Files.exists(normalized)) {
            Object supplied = notifyObjectSourceMissing(objectId);
            if (supplied != null) {
                return new LPCObjectHandle(this, objectId, supplied.getClass(), supplied);
            }
        }

        CompilationResult result = compile(normalized);

        if (!result.getProblems().isEmpty()) {
            throw compilationFailure(objectId, result.getProblems());
        }

        CompilationUnit compilationUnit = result.getCompilationUnit();
        if (compilationUnit != null) {
            defineInheritedClasses(compilationUnit.parentUnit());
        }

        byte[] bytecode = result.getBytecode();
        if (bytecode == null) {
            throw new LPCRuntimeException("Compilation did not produce bytecode for " + objectId);
        }

        String internalName = (result.getAstObject() != null) ? result.getAstObject().name() : jvmInternalName(objectId);
        internalName = jvmInternalName(normalizeInternalName(internalName));
        Class<?> compiledClass = classLoader.defineClass(internalName, bytecode);
        Object instance = instantiate(compiledClass);

        registerObject(objectId, instance);
        resetIfPresent(instance);

        return new LPCObjectHandle(this, objectId, compiledClass, instance);
    }

    /** Compiles one source file using this runtime's include, efun, and mudlib boundary context. */
    public CompilationResult compile(Path sourcePath) {
        Objects.requireNonNull(sourcePath, "sourcePath");
        Path normalized = resolveSourcePathWithExtensions(sourcePath);
        String source;

        try {
            if (!Files.exists(normalized)) {
                String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
                String message = "Source file not found: " + normalized;
                notifyCompilationError(objectId, message);
                throw new LPCRuntimeException(message);
            }
            source = Files.readString(normalized);
        } catch (IOException e) {
            String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
            String message = "Failed to read source file: " + normalized;
            notifyCompilationError(objectId, message + ": " + e.getMessage());
            throw new LPCRuntimeException(message, e);
        }

        String objectId = normalizeInternalName(deriveSourceName(normalized, sourceNameBasePath(normalized)));
        String displayPath = "/" + objectId;
        return pipeline.run(normalized, source, jvmInternalName(objectId), displayPath, ParserOptions.defaults());
    }

